#!/usr/bin/env bash
# fleet P5: switchboard cross-machine channel. The remote machine executes;
# the ledger never leaves this one. Cases 6-7 use the local node as its own
# remote, so a second machine is not needed and CI can run them.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export FLEET_HOME="$(mktemp -d /var/tmp/fleet-p5-test-XXXX)"
trap 'rm -rf "$FLEET_HOME"' EXIT
export PATH="$ROOT/bin:$PATH"

PASS=0
FAIL=0
N=0
ok(){ N=$((N+1)); echo "ok $N - $1"; PASS=$((PASS+1)); }
no(){ N=$((N+1)); echo "not ok $N - $1"; FAIL=$((FAIL+1)); }
skip(){ N=$((N+1)); echo "ok $N - $1 # SKIP $2"; PASS=$((PASS+1)); }
field(){ fleet show "$1" | awk -v f="$2" '$1==f":"{print $2}'; }
wait_settled(){ local id="$1" i s; for i in $(seq 1 300); do
  s=$(field "$id" status)
  case "$s" in done|failed|cancelled) return 0;; esac; sleep 0.5; done; return 1; }

fleet init >/dev/null
HAVE_SB=1
command -v switchboard >/dev/null 2>&1 || HAVE_SB=0
SELF=""
if [ "$HAVE_SB" = "1" ]; then
  SELF=$(switchboard nodes --json 2>/dev/null \
         | python3 -c 'import json,sys
try: print(next(n["name"] for n in json.load(sys.stdin) if n.get("self")))
except Exception: print("")' 2>/dev/null)
fi

# 1. nodes: text lists this machine, --json is valid JSON
if [ "$HAVE_SB" = "1" ] && [ -n "$SELF" ]; then
  if fleet nodes | grep -q "^$SELF " \
     && fleet nodes --json | python3 -c 'import json,sys; json.load(sys.stdin)'; then
    ok "nodes lists this machine and --json parses"
  else
    no "nodes lists this machine and --json parses"
  fi
else
  skip "nodes lists this machine and --json parses" "no switchboard"
fi

# 2/3. a node that does not exist is refused at enqueue, not at run time --
# discovering it hours later inside a failed job helps nobody. The escape
# hatch exists for a node that is merely down right now.
python3 - "$FLEET_HOME/channels.json" <<'PY'
import json, sys
p = sys.argv[1]; d = json.load(open(p))
d["channels"]["sb-missing"] = {"family": "none", "adapter": "switchboard.sh",
                               "node": "fleet-no-such-node-xyz", "remote_cmd": "cat"}
json.dump(d, open(p, "w"), indent=2)
PY
printf 'hello from p5\n' > "$FLEET_HOME/spec.md"
if [ "$HAVE_SB" = "1" ]; then
  fleet add "missing node" --channel sb-missing --spec "$FLEET_HOME/spec.md" \
    >/dev/null 2>"$FLEET_HOME/e2"
  rc2=$?
  M3=$(fleet add "missing node anyway" --channel sb-missing --allow-offline \
       --spec "$FLEET_HOME/spec.md" 2>/dev/null)
  [ "$rc2" = "4" ] && ok "unknown node refused with exit 4" \
                   || no "unknown node refused with exit 4 (rc=$rc2)"
  [ -n "$M3" ] && ok "--allow-offline enqueues anyway" \
               || no "--allow-offline enqueues anyway"
  fleet cancel "$M3" >/dev/null 2>&1 || true
else
  skip "unknown node refused with exit 4" "no switchboard"
  skip "--allow-offline enqueues anyway" "no switchboard"
fi

# 4. the prompt travels as a file. A detached job has no stdin, and putting
# the prompt in argv would also publish it in the remote process table.
d4=$(FLEET_ADAPTER_DRYRUN=1 FLEET_ATTEMPT=p5-attempt-4 FLEET_SB_NODE=somenode FLEET_SB_REMOTE_CMD=cat \
     FLEET_SB_MCP_CMD='switchboard exec home "env fleet-mcp"' \
     bash "$ROOT/adapters/switchboard.sh" 9 "$FLEET_HOME/spec.md" /var/tmp \
     "$FLEET_HOME/o" "$FLEET_HOME/l" 2>&1)
if echo "$d4" | grep -q "switchboard cp" \
   && echo "$d4" | grep -q -- "exec somenode --detach" \
   && echo "$d4" | grep -q "switchboard wait" \
   && ! echo "$d4" | grep -q "hello from p5"; then
  ok "dryrun: cp + detach + wait, prompt never in argv"
else
  no "dryrun: cp + detach + wait, prompt never in argv"
fi

# 5. the callback command is generated by bin/fleet, not invented by the
#    test: `fleet _mcp-callback` prints what launch() hands the adapter, and
#    the dryrun must carry THAT command. The old assertion grepped a string
#    the test itself put in FLEET_SB_MCP_CMD -- self-proving, it passed with
#    any adapter that echoed its env. Quote characters are stripped before
#    comparing so the assertion is robust to the adapter's shell-quoting.
T5=$(fleet add "cb probe" --channel shell --spec "$FLEET_HOME/spec.md")
CB=$(FLEET_SB_SELF=test-self fleet _mcp-callback "$T5")
rc5=$?
d5=$(FLEET_ADAPTER_DRYRUN=1 FLEET_ATTEMPT=p5-attempt-5 FLEET_SB_NODE=somenode FLEET_SB_REMOTE_CMD=cat \
     FLEET_SB_MCP_CMD="$CB" \
     bash "$ROOT/adapters/switchboard.sh" 9 "$FLEET_HOME/spec.md" /var/tmp \
     "$FLEET_HOME/o5" "$FLEET_HOME/l5" 2>&1)
d5flat=$(printf '%s' "$d5" | tr -d "'\\")
cbflat=$(printf '%s' "$CB" | tr -d "'\\")
if [ "$rc5" = "0" ] \
   && printf '%s\n' "$CB" | grep -q '^switchboard exec test-self ' \
   && printf '%s\n' "$CB" | grep -qF "FLEET_TASK_ID=$T5" \
   && printf '%s\n' "$CB" | grep -q 'fleet-mcp' \
   && printf '%s' "$d5flat" | grep -qF "$cbflat"; then
  ok "dryrun carries the bin/fleet-generated callback verbatim"
else
  no "dryrun carries the bin/fleet-generated callback verbatim (cb=$CB d5=$d5)"
fi

# 6. real round trip over the loopback node: prompt out, output back.
if [ "$HAVE_SB" = "1" ] && [ -n "$SELF" ]; then
  python3 - "$FLEET_HOME/channels.json" "$SELF" <<'PY'
import json, sys
p, self_node = sys.argv[1], sys.argv[2]
d = json.load(open(p))
d["channels"]["sb-loop"] = {"family": "none", "adapter": "switchboard.sh",
                            "node": self_node, "remote_cmd": "cat"}
json.dump(d, open(p, "w"), indent=2)
PY
  T6=$(fleet add "loopback" --channel sb-loop --spec "$FLEET_HOME/spec.md" --cwd /var/tmp)
  fleet run "$T6" >/dev/null
  if wait_settled "$T6" && [ "$(field "$T6" status)" = "done" ] \
     && fleet digest "$T6" | grep -q "hello from p5"; then
    ok "loopback round trip: prompt out, output back, exit 0"
  else
    no "loopback round trip: prompt out, output back, exit 0 (status=$(field "$T6" status))"
  fi
else
  skip "loopback round trip: prompt out, output back, exit 0" "no switchboard self node"
fi

# 7. the callback really writes this machine's ledger from the remote side.
if [ "$HAVE_SB" = "1" ] && [ -n "$SELF" ]; then
  cat > "$FLEET_HOME/mcpspec.md" <<'MSG'
{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"p5","version":"1"}}}
{"jsonrpc":"2.0","id":2,"method":"tools/call","params":{"name":"fleet_claim","arguments":{"claim":"remote side reached the local ledger","evidence":"filed over the switchboard callback from the loopback node"}}}
MSG
  python3 - "$FLEET_HOME/channels.json" "$SELF" <<'PY'
import json, sys
p, self_node = sys.argv[1], sys.argv[2]
d = json.load(open(p))
# remote_cmd pipes the prompt into the callback: exactly how a real agent's
# MCP client would be wired, minus the agent.
d["channels"]["sb-mcp"] = {"family": "none", "adapter": "switchboard.sh",
                           "node": self_node,
                           # single quotes on purpose: the callback is expanded by
                           # the inner shell from the environment the assignment
                           # prefix set. Double quotes would let the outer remote
                           # shell expand it first -- to nothing, silently.
                           "remote_cmd": "sh -c 'eval \"$FLEET_SB_MCP_CMD\"'"}
json.dump(d, open(p, "w"), indent=2)
PY
  T7=$(fleet add "remote mcp" --channel sb-mcp --spec "$FLEET_HOME/mcpspec.md" --cwd /var/tmp)
  fleet run "$T7" >/dev/null
  wait_settled "$T7"
  n=$(python3 -c "
import sqlite3
c=sqlite3.connect('$FLEET_HOME/fleet.db')
print(c.execute(\"SELECT COUNT(*) FROM claim WHERE task_id=$T7 AND evidence<>''\").fetchone()[0])")
  [ "$n" -ge 1 ] && ok "remote MCP callback writes a claim into the local ledger" \
                 || no "remote MCP callback writes a claim into the local ledger (claims=$n, status=$(field "$T7" status))"
else
  skip "remote MCP callback writes a claim into the local ledger" "no switchboard self node"
fi

# 8. an unreachable node fails the task; it must never look like success.
if [ "$HAVE_SB" = "1" ]; then
  T8=$(fleet add "dead node" --channel sb-missing --allow-offline \
       --spec "$FLEET_HOME/spec.md" --cwd /var/tmp)
  fleet run "$T8" >/dev/null 2>&1
  wait_settled "$T8"
  st=$(field "$T8" status); ec=$(field "$T8" exit_code)
  if [ "$st" = "failed" ] && [ "$ec" != "0" ]; then
    ok "unreachable node fails the task with a non-zero code"
  else
    no "unreachable node fails the task with a non-zero code (status=$st exit=$ec)"
  fi
else
  skip "unreachable node fails the task with a non-zero code" "no switchboard"
fi

# 9. project-agnostic
PAT="${FLEET_FORBIDDEN_NAMES:-Acme""Corp|acme""-internal}"
if grep -rIn -E "$PAT" "$ROOT" --exclude-dir=.git --exclude-dir=docs; then
  no "project-agnostic: no concrete project names"
else
  ok "project-agnostic: no concrete project names"
fi

echo "---"
echo "passed $PASS / $((PASS+FAIL))"
[ "$FAIL" = "0" ]
